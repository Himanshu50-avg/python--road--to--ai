# SLICING

s ='himanshu'
print(s)
print(len(s))  #length of string
print(s[0:8])  #getting character upto 7 index
print(s[:5])     # starting from index[0]
print(s[1:])     #  goes upto last index of len

# print(s[0:8:2])  #slicing with skiping char
print(s[-1:-9:-1])  #negative slicing

