
class calculator:
    def __init__(self,n):
        self.n=n


    def sqaure(self):
        print(f"SQUARE IS {self.n*self.n}")
    def cube(kk):
            print(f"CUBE IS {kk.n*kk.n*kk.n}")  #no problem with changing self
    
    def sqaureroot(self):
            print(f"SQUAREROOT IS {self.n**1/2}")
    
    
a=calculator(4)
a.sqaure()
a.cube()
a.sqaureroot()